export function resolveDeckLang(search = '', saved = '', browserLang = '') {
  try {
    const params = new URLSearchParams(search || '');
    const q = (params.get('lang') || '').toLowerCase();
    if (q === 'en' || q === 'ru') return q;
  } catch {}
  if (saved === 'en' || saved === 'ru') return saved;
  if (String(browserLang || '').toLowerCase().startsWith('ru')) return 'ru';
  return 'en';
}

export function tDeck(lang, key, vars = null) {
  const dict = DECK_I18N[lang === 'en' ? 'en' : 'ru'] || DECK_I18N.en;
  let str = dict[key] !== undefined ? dict[key] : (DECK_I18N.en[key] ?? key);
  if (vars && typeof vars === 'object') {
    for (const [k, v] of Object.entries(vars)) {
      str = str.replaceAll(`{${k}}`, String(v ?? ''));
    }
  }
  return str;
}
